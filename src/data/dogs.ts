import type { BattleTrait } from '../logic/battle';

/**
 * 官方已釋放的狗狗武將。前 5 隻依 docs/GDD.md，玩家一開始就擁有（見 STARTER_DOG_IDS）；
 * 其他的要到主頁「召募」抽（T007，規則在 src/logic/gacha.ts），沒擁有的在組隊畫面以暗色顯示。
 * 補血狗「暖桶」不靠召募，第一次打贏第 1 章 Boss 就送（見 regions.ts 的 firstClearDog）；
 * 拿到之後才會進召募池（重複抽到換碎片，才能升星）。
 * T007 新增的 10 隻、T024 新增的 11 隻（共 30 隻，六種定位各 5 隻、各有 SSR）犬種取自 docs/BREEDS.md，
 * 名字、性格、技能都是原創。
 * 技能說明（T023）照定位寫出戰鬥中真正的效果，規則在 src/logic/battle.ts。
 * 純資料，不放公式；戰力由 src/logic/power.ts 計算。
 */
export type DogRole =
  '隊長／補給' | '前排／突擊' | '前排／守護' | '後排／謀略' | '後排／幸運' | '後排／補血';

/** 稀有度：越後面越稀有、基礎數值越高（T007） */
export type DogRarity = 'N' | 'R' | 'SR' | 'SSR';
/** 體型（T007） */
export type DogSize = '小型' | '中型' | '大型';

export interface DogSkill {
  name: string;
  description: string;
}

export interface DogData {
  id: string;
  /** 代號（顯示名稱） */
  name: string;
  breed: string;
  personality: string;
  role: DogRole;
  /** 佔位圖形主色 */
  color: number;
  /** 耳朵／點綴色 */
  accent: number;
  baseAttack: number;
  baseDefense: number;
  level: number;
  skill: DogSkill;
  /** 稀有度（T007 起每隻都有） */
  rarity?: DogRarity;
  /** 體型（T007 起每隻都有） */
  size?: DogSize;
  /** 屬性：等 T017 設計相剋時再填 */
  element?: string;
  /** 攻擊後補血（暖桶專屬）：每次攻擊完接著補血量最低的兩位隊友 */
  afterHeal?: boolean;
  /** 關卡通關送的狗：沒拿到之前不會出現在召募池 */
  rewardOnly?: boolean;
  /** 專屬特性（T024）：戰鬥中多一點自己的打法，規則在 src/logic/battle.ts 的 BattleTrait */
  trait?: BattleTrait;
}

